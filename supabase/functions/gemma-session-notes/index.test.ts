Deno.test('extractGoogleAINoteResult: extracts structured note from function call', () => {
  const mockResponse = {
    candidates: [{
      content: {
        parts: [{
          functionCall: {
            name: 'submit_session_note',
            args: {
              presenting_issue: 'Workplace anxiety',
              session_focus: 'CBT — identifying cognitive distortions',
              key_observations: ['Catastrophising identified', 'Good rapport established'],
              follow_up_actions: ['Thought diary', 'Review ABC model'],
              mood_rating: 'improved',
            },
          },
        }],
        role: 'model',
      },
    }],
  };

  const note = extractGoogleAINoteResult(mockResponse);
  assertExists(note);
  assertEquals(note!.presenting_issue, 'Workplace anxiety');
  assertEquals(note!.key_observations.length, 2);
  assertEquals(note!.mood_rating, 'improved');
});

Deno.test('extractGoogleAINoteResult: returns null when no function call', () => {
  const mockResponse = {
    candidates: [{
      content: {
        parts: [{ text: 'Here is the session note...' }],
        role: 'model',
      },
    }],
  };

  const note = extractGoogleAINoteResult(mockResponse);
  assertEquals(note, null);
});


Deno.test('buildContextPrompt: includes session format and duration', () => {
  const prompt = buildContextPrompt({
    scheduled_at: '2026-05-17T10:00:00Z',
    session_format: 'Video',
    duration_minutes: 60,
  });

  assertMatch(prompt, /Format: Video/);
  assertMatch(prompt, /Duration: 60 minutes/);
});

Deno.test('buildContextPrompt: includes client notes when present', () => {
  const prompt = buildContextPrompt({
    scheduled_at: '2026-05-17T10:00:00Z',
    notes_client: 'Feeling overwhelmed at work this week',
  });

  assertMatch(prompt, /Feeling overwhelmed at work this week/);
});

Deno.test('buildContextPrompt: omits client notes section when null', () => {
  const prompt = buildContextPrompt({
    scheduled_at: '2026-05-17T10:00:00Z',
    notes_client: null,
  });

  assertEquals(prompt.includes('Client notes before session'), false);
});

Deno.test('buildContextPrompt: includes triage data when available', () => {
  const prompt = buildContextPrompt(
    { scheduled_at: '2026-05-17T10:00:00Z' },
    { presenting_issue: 'anxiety', urgency: 'moderate', summary: 'Work-related stress' },
  );

  assertMatch(prompt, /Intake presenting issue: "anxiety"/);
  assertMatch(prompt, /Intake urgency level: moderate/);
  assertMatch(prompt, /Intake summary: "Work-related stress"/);
});

Deno.test('buildContextPrompt: omits triage section when not available', () => {
  const prompt = buildContextPrompt({ scheduled_at: '2026-05-17T10:00:00Z' }, null);

  assertEquals(prompt.includes('Intake'), false);
});

Deno.test('buildContextPrompt: defaults duration to 50 minutes', () => {
  const prompt = buildContextPrompt({ scheduled_at: '2026-05-17T10:00:00Z' });
  assertMatch(prompt, /Duration: 50 minutes/);
});

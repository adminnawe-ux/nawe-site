Deno.test('buildNoteMarkdown: includes all required sections', () => {
  const note: SessionNote = {
    presenting_issue: 'Anxiety and workplace stress',
    session_focus: 'Cognitive reframing techniques',
    key_observations: ['Client showed awareness of triggers', 'Avoidance patterns identified'],
    follow_up_actions: ['Practice breathing exercises', 'Journal daily triggers'],
    mood_rating: 'improved',
  };

  const md = buildNoteMarkdown(note);
  assertMatch(md, /## Presenting Issue/);
  assertMatch(md, /## Session Focus/);
  assertMatch(md, /## Key Observations/);
  assertMatch(md, /## Follow-Up Actions/);
  assertMatch(md, /## Client Mood/);
  assertMatch(md, /Generated by Gemma 4/);
});

Deno.test('buildNoteMarkdown: key_observations rendered as bullet list', () => {
  const note: SessionNote = {
    presenting_issue: 'Depression',
    session_focus: 'Behavioural activation',
    key_observations: ['Low energy reported', 'Sleep disruption noted'],
    follow_up_actions: ['Daily walk goal'],
  };

  const md = buildNoteMarkdown(note);
  assertMatch(md, /- Low energy reported/);
  assertMatch(md, /- Sleep disruption noted/);
});

Deno.test('buildNoteMarkdown: omits mood section when not provided', () => {
  const note: SessionNote = {
    presenting_issue: 'Stress',
    session_focus: 'Stress management',
    key_observations: ['Client engaged well'],
    follow_up_actions: ['Mindfulness exercise'],
  };

  const md = buildNoteMarkdown(note);
  assertEquals(md.includes('## Client Mood'), false);
});

Deno.test('buildNoteMarkdown: follow_up_actions rendered as bullet list', () => {
  const note: SessionNote = {
    presenting_issue: 'Anxiety',
    session_focus: 'Exposure therapy intro',
    key_observations: ['Motivation present'],
    follow_up_actions: ['Rate anxiety daily', 'Try one avoided activity'],
  };

  const md = buildNoteMarkdown(note);
  assertMatch(md, /- Rate anxiety daily/);
  assertMatch(md, /- Try one avoided activity/);
});


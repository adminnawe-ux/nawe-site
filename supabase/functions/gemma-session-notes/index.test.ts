Deno.test('extractOllamaNoteResult: extracts structured note from tool call', () => {
  const mockResponse = {
    message: {
      role: 'assistant',
      content: '',
      tool_calls: [{
        function: {
          name: 'submit_session_note',
          arguments: {
            presenting_issue: 'Grief after bereavement',
            session_focus: 'Normalising grief responses',
            key_observations: ['Tearful but engaged', 'Support network limited'],
            follow_up_actions: ['Contact one friend this week'],
            mood_rating: 'neutral',
          },
        },
      }],
    },
  };

  const note = extractOllamaNoteResult(mockResponse);
  assertExists(note);
  assertEquals(note!.presenting_issue, 'Grief after bereavement');
  assertEquals(note!.mood_rating, 'neutral');
});

Deno.test('extractOllamaNoteResult: returns null when no tool call', () => {
  const mockResponse = {
    message: { role: 'assistant', content: 'Here is a note...' },
  };

  assertEquals(extractOllamaNoteResult(mockResponse), null);
});

